    private void upload_buttonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_upload_buttonActionPerformed
        JFileChooser fileChooser = new JFileChooser();
        fileChooser.setFileFilter(new javax.swing.filechooser.FileNameExtensionFilter("Image files", "jpg", "png", "jpeg"));
        int result = fileChooser.showOpenDialog(this);
        if (result == JFileChooser.APPROVE_OPTION) {
            selectedPhoto = fileChooser.getSelectedFile();
            photo_textfield.setText(selectedPhoto.getAbsolutePath());
            JOptionPane.showMessageDialog(this, "Photo uploaded: " + selectedPhoto.getName());
        }
    }//GEN-LAST:event_upload_buttonActionPerformed

    private void submit_buttonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_submit_buttonActionPerformed
        String firstName = firstname_textfield.getText().trim();
        String lastName = lastname_textfield.getText().trim();
        String gender = gender_box.getSelectedItem().toString();
        int age = (Integer) age_spinner.getValue();
        String phone = phonenumber_textfield.getText().trim();
        String phoneDigits = phone.replaceAll("\\D", "");
        String email = email_text.getText().trim();
        String continent = continent_box.getSelectedItem().toString();
        String experience = experience_textarea.getText().trim();

        if (firstName.isEmpty()) {
            showError("Please enter your First Name.");
            firstname_textfield.requestFocus();
            return;
        }
        if (!firstName.matches("[A-Za-z ]+")) {
            showError("First Name should contain only letters.");
            firstname_textfield.requestFocus();
            return;
        }
        if (lastName.isEmpty()) {
            showError("Please enter your Last Name.");
            lastname_textfield.requestFocus();
            return;
        }
        if (!lastName.matches("[A-Za-z ]+")) {
            showError("Last Name should contain only letters.");
            lastname_textfield.requestFocus();
            return;
        }
        if (age <= 0 || age > 120) {
            showError("Please enter a valid age (1-120).");
            age_spinner.requestFocus();
            return;
        }
        if (email.isEmpty()) {
            showError("Please enter your Email.");
            email_text.requestFocus();
            return;
        }
        if (!email.matches("^[\\w.-]+@([\\w-]+\\.)+[\\w-]{2,}$")) {
            showError("Invalid email format!");
            email_text.requestFocus();
            return;
        }
        if (phoneDigits.isEmpty()) {
            showError("Please enter your Phone Number.");
            phonenumber_textfield.requestFocus();
            return;
        }
        if (!phoneDigits.matches("\\d{10}")) {
            showError("Invalid phone number! Enter all 10 digits (123-456-7890).");
            phonenumber_textfield.requestFocus();
            return;
        }
        if (experience.isEmpty()) {
            showError("Please enter your Experience.");
            experience_textarea.requestFocus();
            return;
        }
        if (selectedPhoto == null) {
            showError("Please upload a photo!");
            return;
        }

        User user = new User(firstName, lastName, gender, age, phone, email, continent, experience, selectedPhoto);

        ImageIcon icon = new ImageIcon(new ImageIcon(selectedPhoto.getAbsolutePath())
                .getImage().getScaledInstance(120, 120, java.awt.Image.SCALE_SMOOTH));
        JOptionPane.showMessageDialog(this, user.toString(), "Profile", JOptionPane.INFORMATION_MESSAGE, icon);
    }//GEN-LAST:event_submit_buttonActionPerformed

    private void showError(String message) {
        JOptionPane.showMessageDialog(this, message, "Error", JOptionPane.ERROR_MESSAGE);
    }

